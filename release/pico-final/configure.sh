#!/usr/bin/env bash
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
build=${1:?Usage: configure.sh BUILD_DIR [CMake overrides]}
shift
cmake -S "$root/source/platform/rp2040/router" -B "$build" -G Ninja \
    -DCMAKE_BUILD_TYPE=MinSizeRel -DCMAKE_EXPORT_COMPILE_COMMANDS=ON \
    -DPICO_BOARD=waveshare_rp2040_zero -DPICO_COPY_TO_RAM=OFF \
    -DPICO_SDK_PATH=/opt/pico/pico-sdk -DPICO_TINYUSB_PATH=/opt/pico/tinyusb-0.21.0 \
    -DPICO_PIO_USB_PATH=/opt/pico/Pico-PIO-USB \
    -Dpioasm_DIR=/workspace/gridpico/build/rp2040-onboard-status/pioasm-install/pioasm \
    -DGRIDPICO_RP2040_BENCH_TRACE=ON -DGRIDPICO_RP2040_PIO_DIAGNOSTICS=ON \
    -DGRIDPICO_RP2040_HCD_TRACE=ON -DGRIDPICO_RP2040_HUB_TRACE=ON \
    -DGRIDPICO_RP2040_TWO_HUB_BENCH=ON -DGRIDPICO_RP2040_PATCHBAY_BENCH=ON \
    -DGRIDPICO_RP2040_FLASH_ROUTER=ON -DGRIDPICO_RP2040_FLASH_STARTUP_FAULT=OFF \
    -DGRIDPICO_RP2040_PROGRAM_CHANGE_BENCH=OFF -DGRIDPICO_RP2040_KEYS_BENCH=OFF \
    -DGRIDPICO_RP2040_PAT2_LINK_FIXTURE=OFF -DGRIDPICO_RP2040_PAT2_BOOT_READ=ON \
    -DGRIDPICO_RP2040_PICO7_NORMAL=ON -DGRIDPICO_RP2040_ROUTING_PAGES=ON \
    -DGRIDPICO_RP2040_ROUTING_BITMAP=ON -DGRIDPICO_RP2040_PANIC_CC123=ON \
    -DGRIDPICO_RP2040_READONLY_USB_DRIVE=ON \
    -DGRIDPICO_RP2040_USB_DRIVE_ASSET_DIR="$root/staged-assets" "$@"
